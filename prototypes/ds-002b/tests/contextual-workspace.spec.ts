import { expect, test } from '@playwright/test'
import type { Locator, Page } from '@playwright/test'

const add = (page: Page) => page.getByRole('button', { name: 'კომპონენტის დამატება' })
const shelf = (page: Page) => page.getByRole('region', { name: 'კომპონენტების ბიბლიოთეკა' })
const search = (page: Page) => shelf(page).getByRole('searchbox', { name: 'ძებნა' })
const inspector = (page: Page) => page.getByRole('complementary', { name: 'Workspace inspector' })
const close = (panel: Locator) => panel.getByRole('button', { name: 'დახურვა', exact: true })
const canvas = (page: Page) => page.locator('.react-flow')
const viewport = (page: Page) => page.locator('.react-flow__viewport')
const part = (page: Page, id: string) => canvas(page).locator('.react-flow__node[data-id="' + id + '"]')
const pin = (page: Page, id: string) => canvas(page).getByRole('button', { name: id, exact: true })
const edge = (page: Page) => canvas(page).locator('.react-flow__edge-path')
const place = (page: Page, name: string) => shelf(page).getByRole('button', { name: name + ' — მოთავსება' })

async function addPart(page: Page, name: string) {
  await add(page).click()
  await place(page, name).click()
  await expect(shelf(page)).toBeHidden()
  await expect(add(page)).toBeFocused()
}

async function pair(page: Page) {
  await addPart(page, 'HC-SR04')
  await addPart(page, 'LED')
  await expect(pin(page, 'sensor/TRIG')).toBeVisible()
  await expect(pin(page, 'led/A')).toBeVisible()
}

async function connect(page: Page) {
  await pin(page, 'sensor/TRIG').click()
  await pin(page, 'led/A').click()
  await expect(edge(page)).toHaveCount(1)
}

async function pathPoints(page: Page, ratios: number[]) {
  return edge(page).evaluate((element, fractions) => {
    const path = element as SVGPathElement
    const matrix = path.getScreenCTM()!
    return fractions.map(fraction => {
      const { x, y } = path.getPointAtLength(fraction * path.getTotalLength()).matrixTransform(matrix)
      return { x, y }
    })
  }, ratios)
}

async function bounds(locator: Locator) {
  const box = await locator.boundingBox()
  if (!box) throw Error('Expected visible geometry for ' + locator)
  return box
}

async function endpointError(page: Page) {
  const endpoints = await pathPoints(page, [0, 1])
  const handles = await Promise.all(['sensor/TRIG', 'led/A'].map(id => bounds(pin(page, id))))
  return Math.max(...handles.map(({ x, y, width, height }, i) =>
    Math.hypot(x + width / 2 - endpoints[i].x, y + height / 2 - endpoints[i].y)))
}

const transform = (locator: Locator) => locator.evaluate(node => getComputedStyle(node).transform)
const panelPlacement = (locator: Locator) => locator.evaluate(node => {
  const css = getComputedStyle(node)
  return { position: css.position, maxHeight: css.maxHeight, overflow: css.overflowY }
})

test('UXB-01 full-width canvas, contextual overlay geometry and legacy structure', async ({ page }) => {
  await page.goto('/?ux=entry')
  const header = await bounds(page.locator('.topbar'))
  const initial = await bounds(canvas(page))
  expect(header.height).toBe(56)
  expect(initial.width).toBe(1440)
  expect(initial.x).toBe(0)
  await expect(inspector(page)).toBeHidden()
  await expect(page.getByText('დაიწყე კომპონენტის დამატებით', { exact: true })).toBeVisible()
  await expect.poll(() => transform(viewport(page))).not.toBe('none')
  const before = await transform(viewport(page))
  await add(page).click()
  await expect.poll(async () => (await bounds(shelf(page))).y).toBe(header.y + header.height + 16)
  expect(await bounds(shelf(page))).toMatchObject({ x: 16, width: 320 })
  expect(await panelPlacement(shelf(page))).toEqual({ position: 'absolute', maxHeight: '630px', overflow: 'auto' })
  expect(await bounds(canvas(page))).toEqual(initial)
  expect(await transform(viewport(page))).toBe(before)
  await place(page, 'HC-SR04').click()
  await expect(page.getByText('დაიწყე კომპონენტის დამატებით')).toBeHidden()
  await expect(inspector(page)).toBeHidden()
  await pin(page, 'sensor/TRIG').click()
  const bottom = initial.y + initial.height - 58
  await expect.poll(async () => {
    const box = await bounds(inspector(page))
    return box.y + box.height
  }).toBe(bottom)
  expect(await bounds(inspector(page))).toMatchObject({ x: 1440 - 16 - 296, width: 296 })
  expect(await panelPlacement(inspector(page))).toEqual({ position: 'absolute', maxHeight: '540px', overflow: 'auto' })
  expect(await bounds(canvas(page))).toEqual(initial)
  expect(await transform(viewport(page))).toBe(before)
  await close(inspector(page)).click()
  expect(await bounds(canvas(page))).toEqual(initial)
  expect(await transform(viewport(page))).toBe(before)
  await page.goto('/')
  await expect(inspector(page)).toBeVisible()
  expect((await bounds(canvas(page))).width).toBe(1440 - 252)
  await expect(page.locator('.react-flow__node')).toHaveCount(4)
  await expect(page.getByText('Visual workspace JSON', { exact: true })).toBeVisible()
  await expect(add(page)).toHaveCount(0)
})

