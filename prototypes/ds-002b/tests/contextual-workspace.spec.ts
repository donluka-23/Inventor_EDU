test('UXB-08 legacy and contextual interaction use local assets without runtime errors', async ({ page, baseURL }) => {
  const errors: string[] = []
  const external: string[] = []
  const experimentalBoardImages: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    const url = new URL(request.url())
    if (!['data:', 'blob:'].includes(url.protocol) && url.origin !== new URL(baseURL!).origin) external.push(url.href)
    if (page.url().endsWith('/?ux=entry') && request.resourceType() === 'image' && url.pathname.includes('devkitc-v4')) {
      experimentalBoardImages.push(url.href)
    }
  })
  await page.goto('/')
  await expect(canvas(page).locator('[data-terminal]')).toHaveCount(46)
  await expect(inspector(page)).toBeVisible()
  await page.goto('/?ux=entry')
  await pair(page)
  await connect(page)
  await close(inspector(page)).click()
  await add(page).click()
  await place(page, 'Resistor').click()
  await expect(part(page, 'resistor').locator('[data-terminal]')).toHaveCount(2)
  expect(errors).toEqual([])
  expect(external).toEqual([])
  expect(experimentalBoardImages).toEqual([])
})
