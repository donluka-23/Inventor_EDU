test('UXB-05 wiring follows the real renderer across drag, zoom and undo/redo', async ({ page }) => {
  await page.goto('/?ux=entry')
  await pair(page)
  await connect(page)
  const original = await edge(page).getAttribute('d')
  await close(inspector(page)).click()
  const label = await bounds(part(page, 'led').locator('.part-label'))
  const x = label.x + label.width / 2
  const y = label.y + label.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 70, y + 35, { steps: 10 })
  await page.mouse.up()
  await expect(edge(page)).not.toHaveAttribute('d', original!)
  for (const zoom of [0.5, 1, 2]) {
    await page.getByRole('button', { name: 'Zoom ' + zoom + 'x', exact: true }).click()
    await expect(page.getByLabel('Current zoom')).toHaveText(zoom * 100 + '%')
    await expect.poll(() => endpointError(page)).toBeLessThan(2)
    console.log('UXB sensor/TRIG–led/A at ' + zoom + '×: ' + (await endpointError(page)).toFixed(4) + ' CSS px')
  }
  await page.getByRole('button', { name: /Undo/ }).click()
  await expect(edge(page)).toHaveCount(0)
  await page.getByRole('button', { name: /Redo/ }).click()
  await expect(edge(page)).toHaveCount(1)
  await expect.poll(() => endpointError(page)).toBeLessThan(2)
})

